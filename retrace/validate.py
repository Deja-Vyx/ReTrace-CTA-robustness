"""Validity checks for variants.

Three layers always run (no GPU/LLM needed); layer 4 is optional:
  1. IOC preservation: the infrastructure IOC set (excluding Protocol/Port/Account) of the original
     == that of the variant, except for operators that change IOCs by design (E1, E7, E8); E2 drop
     may only lose IOCs (IOCs in the removed sentences are recorded), never add new ones.
  2. Cheap constraints: length ratio (INV operators only), no new group names, INV 1 sentence -> 1 sentence.
  3. Correct target: E2 removes exactly the targeted techniques; E4 masks at least one mention...
  4. (optional) bidirectional NLI + LLM judge for INV operators.

export-human: export a CSV for human annotators; kappa: Cohen's kappa between two annotations.

    python -m retrace.validate export-human --run full --n 150
    python -m retrace.validate kappa --a human_A.csv --b human_B.csv
    python -m retrace.validate nli --run llm     # bidirectional entailment for T1/T2 (DeBERTa-MNLI)
"""
import argparse
import csv
import random

from src.ioc_extract import extract_iocs
from src.utils import sent_split
from .common import HUMAN_DIR, iter_jsonl_any
from .lexicons import dataset_groups, find_any_group_mentions

# operators that change the IOC set by design -> no IOC-equality constraint
IOC_CHANGING = {"E1", "E7", "E8"}
# INV operators that must keep the sentence count
STRICT_ALIGN = {"ID", "T1", "T3", "T6", "E3"}


# Protocol/Port/Account are generic strings (RDP, 443, admin), not attack infrastructure; they are
# excluded from IOC preservation (the T3 regex intentionally rewrites them).
NON_INFRA = {"Protocol", "Port", "Account"}


def _ioc_set(text: str) -> set:
    return {(i["type"], i["value"].lower()) for i in extract_iocs(text) if i["type"] not in NON_INFRA}


def check_variant(orig_text: str, v, cfg: dict) -> dict:
    """v is a Variant with v.text (levels 1-2). Returns {passed, checks}."""
    checks = {}
    text = v.text
    if text is None:
        return {"passed": True, "checks": {"graph_level": True}}

    o_ioc, n_ioc = _ioc_set(orig_text), _ioc_set(text)
    removes_sents = v.op == "E2" and (v.params or {}).get("mode", "drop") == "drop"
    if v.op in IOC_CHANGING:
        checks["ioc_superset_or_sub"] = True
    elif removes_sents:
        # E2 drop removes whole sentences -> their IOCs are lost (recorded), but no new IOC may appear
        checks["ioc_no_new"] = n_ioc.issubset(o_ioc)
        checks["ioc_lost"] = len(o_ioc - n_ioc)
    else:
        checks["ioc_equal"] = (o_ioc == n_ioc)

    lo, hi = cfg.get("validate", {}).get("len_ratio", [0.7, 1.3])
    ratio = len(text) / max(1, len(orig_text))
    checks["len_ratio"] = round(ratio, 3)
    # the length constraint only applies to operators that do NOT add/remove content on purpose (INV);
    # DIR/TGT operators delete or insert evidence, so a length change is by design
    if (v.expect or "INV") == "INV" and v.op not in ("T4", "T5", "E7"):
        checks["len_ok"] = (float(lo) * 0.6 <= ratio <= float(hi) * 1.6)

    # no NEW group names (except E8, by design)
    o_groups = set(find_any_group_mentions(orig_text))
    n_groups = set(find_any_group_mentions(text))
    if v.op != "E8":
        checks["no_new_group"] = n_groups.issubset(o_groups | {v.group})
    else:
        checks["no_new_group"] = True

    if v.op in STRICT_ALIGN:
        checks["single_align"] = (len(sent_split(text)) == len(sent_split(orig_text)))

    hard = [k for k in ("ioc_equal", "ioc_no_new", "len_ok", "no_new_group", "single_align") if k in checks]
    passed = all(bool(checks[k]) for k in hard)
    return {"passed": passed, "checks": checks}


# ---------------------------------------------------------------- NLI + judge (optional)
def nli_bidirectional(pairs, model_name="MoritzLaurer/DeBERTa-v3-base-mnli-fever-anli"):
    from transformers import pipeline as hf_pipeline
    nli = hf_pipeline("text-classification", model=model_name, top_k=None)
    out = []
    for a, b in pairs:
        def ent(x, y):
            r = nli(f"{x} [SEP] {y}")[0]
            d = {t["label"].lower(): t["score"] for t in r}
            return d.get("entailment", 0.0)
        out.append(min(ent(a, b), ent(b, a)))
    return out


def judge_pairs(pairs, cfg):
    from .llm import P_JUDGE, check_judge, get_llm
    llm = get_llm(cfg)
    out = []
    for a, b in pairs:
        r = llm.json(P_JUDGE.format(a=a, b=b), check=check_judge, temperature=0.0, tag="judge")
        out.append(r or {"equivalent": None, "same_actor": None})
    return out


# ---------------------------------------------------------------- NLI for LLM variants (automatic)
NLI_MODEL = "MoritzLaurer/DeBERTa-v3-base-mnli-fever-anli"
NLI_OPS = ("T1", "T2")          # meaning-preserving (INV) operators generated by the LLM


def _edit_pairs(v: dict) -> list:
    return [(e["before"], e["after"]) for e in (v.get("edits") or [])
            if e.get("sent", -1) >= 0 and e.get("before") and e.get("after")]


def cmd_nli(args):
    """Bidirectional semantic equivalence (entailment A->B and B->A) for every sentence rewritten
    by the LLM. A variant's score is the minimum over its edited sentences. Writes
    runs/<run>/tables/nli.csv + nli.json."""
    import json as _json

    import torch
    from transformers import pipeline as hf_pipeline

    from .config import run_dir
    d = run_dir(args.run)
    variants = [v for v in iter_jsonl_any(d / "variants.jsonl.gz")
                if v.get("op") in NLI_OPS and (v.get("valid") or {}).get("passed", True)]
    pairs = sorted({p for v in variants for p in _edit_pairs(v)})
    if not pairs:
        print(f"[nli] run {args.run}: no T1/T2 variants with edited sentences")
        return
    dev = 0 if torch.cuda.is_available() else -1
    nli = hf_pipeline("text-classification", model=args.model, top_k=None, device=dev, truncation=True)
    inputs = [{"text": a, "text_pair": b} for a, b in pairs] + [{"text": b, "text_pair": a} for a, b in pairs]
    res = nli(inputs, batch_size=32)

    def ent(r):
        return next((x["score"] for x in r if x["label"].lower().startswith("entail")), 0.0)
    n = len(pairs)
    score = {pairs[i]: min(ent(res[i]), ent(res[n + i])) for i in range(n)}
    rows = []
    for v in variants:
        ps = _edit_pairs(v)
        if not ps:
            continue
        m = min(score[p] for p in ps)
        rows.append({"vid": v["vid"], "op": v["op"], "params": ",".join(f"{k}={v['params'][k]}" for k in sorted(v["params"])),
                     "n_sents": len(ps), "nli_min": round(float(m), 4), "pass": int(m >= args.threshold)})
    tables = d / "tables"; tables.mkdir(exist_ok=True)
    with open(tables / "nli.csv", "w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0])); w.writeheader(); w.writerows(rows)
    summ = {}
    for op in sorted({r["op"] for r in rows}):
        rs = [r for r in rows if r["op"] == op]
        summ[op] = {"n": len(rs), "pass_rate": round(sum(r["pass"] for r in rs) / len(rs), 4),
                    "median_nli": round(sorted(r["nli_min"] for r in rs)[len(rs) // 2], 4)}
    (tables / "nli.json").write_text(_json.dumps({"model": args.model, "threshold": args.threshold,
                                                  "by_op": summ, "pass_vids": [r["vid"] for r in rows if r["pass"]]},
                                                 indent=1), encoding="utf-8")
    for op, x in summ.items():
        print(f"[nli] {op}: {x['pass_rate']*100:.0f}% of variants with bidirectional entailment >= {args.threshold} "
              f"(n={x['n']}, median {x['median_nli']:.2f})")
    print(f"-> {tables}/nli.csv, nli.json")


# ---------------------------------------------------------------- human eval
def cmd_export_human(args):
    from .config import run_dir
    d = run_dir(args.run)
    variants = list(iter_jsonl_any(d / "variants.jsonl.gz"))
    want = set(args.ops.split(",")) if getattr(args, "ops", None) else None
    variants = [v for v in variants if v.get("op") not in ("ID", "ORIG") and v.get("text")
                and v.get("valid", {}).get("passed", True) and (want is None or v.get("op") in want)]
    by_op = {}
    for v in variants:
        by_op.setdefault(v["op"], []).append(v)
    rng = random.Random(17)
    picks = []
    ops = sorted(by_op)
    while len(picks) < args.n and any(by_op.values()):
        for op in ops:
            if by_op[op]:
                picks.append(by_op[op].pop(rng.randrange(len(by_op[op]))))
                if len(picks) >= args.n:
                    break
    HUMAN_DIR.mkdir(parents=True, exist_ok=True)
    out = HUMAN_DIR / f"human_eval_{args.run}.csv"
    docs = {}
    for r in iter_jsonl_any(d / "variants.jsonl.gz"):
        if r.get("op") == "ORIG":
            docs[r["doc_id"]] = r.get("text", "")
    with open(out, "w", newline="", encoding="utf-8") as f:
        w = csv.writer(f)
        w.writerow(["vid", "op", "group", "orig_excerpt", "variant_excerpt",
                    "same_meaning(1/0)", "same_actor(1/0)", "note"])
        for v in picks:
            orig = docs.get(v["doc_id"], "")
            ps = _edit_pairs(v)[:3]
            osent = " || ".join(a for a, _b in ps) if ps else orig[:300]
            nsent = " || ".join(b for _a, b in ps) if ps else (v.get("text") or "")[:300]
            w.writerow([v["vid"], v["op"], v["group"], osent, nsent, "", "", ""])
    print(f"-> {out} ({len(picks)} pairs). Two annotators fill in same_meaning/same_actor, "
          f"save as human_A.csv / human_B.csv, then run `kappa`.")


def _read_labels(fp, col):
    m = {}
    for r in csv.DictReader(open(fp, encoding="utf-8")):
        v = str(r.get(col, "")).strip()
        if v in ("0", "1"):
            m[r["vid"]] = int(v)
    return m


def cohen_kappa(a: dict, b: dict) -> tuple:
    keys = sorted(set(a) & set(b))
    if not keys:
        return None, 0
    n = len(keys)
    agree = sum(1 for k in keys if a[k] == b[k]) / n
    pa1 = sum(a[k] for k in keys) / n
    pb1 = sum(b[k] for k in keys) / n
    pe = pa1 * pb1 + (1 - pa1) * (1 - pb1)
    kappa = (agree - pe) / (1 - pe) if pe < 1 else 1.0
    return round(kappa, 4), n


def cmd_kappa(args):
    for col in ("same_meaning(1/0)", "same_actor(1/0)"):
        a = _read_labels(args.a, col); b = _read_labels(args.b, col)
        k, n = cohen_kappa(a, b)
        print(f"{col}: Cohen's kappa = {k} over {n} pairs (target >= 0.6)")


def main():
    ap = argparse.ArgumentParser()
    sub = ap.add_subparsers(dest="cmd", required=True)
    p1 = sub.add_parser("export-human"); p1.add_argument("--run", required=True); p1.add_argument("--n", type=int, default=150)
    p1.add_argument("--ops", default="T1,T2", help="operators to annotate (default: meaning-preserving T1,T2)")
    p2 = sub.add_parser("kappa"); p2.add_argument("--a", required=True); p2.add_argument("--b", required=True)
    p3 = sub.add_parser("nli"); p3.add_argument("--run", required=True)
    p3.add_argument("--model", default=NLI_MODEL); p3.add_argument("--threshold", type=float, default=0.5)
    args = ap.parse_args()
    {"export-human": cmd_export_human, "kappa": cmd_kappa, "nli": cmd_nli}[args.cmd](args)


if __name__ == "__main__":
    main()
